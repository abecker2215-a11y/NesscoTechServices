export function getPopularTerms(terms: GlossaryTerm[], count = 6): GlossaryTerm[] {
  return [...terms].sort((a, b) => (b.popularity || 0) - (a.popularity || 0)).slice(0, count);
}

export function getTermBySlug(slug: string): GlossaryTerm | undefined {
  return glossaryTerms.find((t) => t.slug === slug);
}

export function getRelatedTerms(term: GlossaryTerm): GlossaryTerm[] {
  if (!term.relatedTerms) return [];
  return term.relatedTerms
    .map((slug) => getTermBySlug(slug.toLowerCase().replace(/[^a-z0-9]+/g, "-")))
    .filter((t): t is GlossaryTerm => t !== undefined);
}

