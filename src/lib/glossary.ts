export function getCategoryCounts(terms: GlossaryTerm[]) {
  const counts = new Map<GlossaryCategory, number>();
  for (const term of terms) {
    counts.set(term.category, (counts.get(term.category) || 0) + 1);
  }
  return allCategories.map((cat) => ({ ...cat, count: counts.get(cat.value) || 0 }));
}

